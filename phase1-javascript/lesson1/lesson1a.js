// Lesson 1a: variables, types and template literals

// --- Variables ---
const name = "Maruf";
const age = 22;
const student = true;

// I used let for semester as it changes later from 1 to 2
let semester = 1;
semester++;

// --- Template literal ---
console.log(`My name is ${name} and I am ${age} years old.`);

// --- Types ---
console.log(typeof name);
console.log(typeof age);
console.log(typeof student);
console.log(typeof semester);
